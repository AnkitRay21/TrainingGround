
import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# Plate geometry
# ============================================================

Lx = 0.20          # m
Ly = 0.10          # m

Nx = 51
Ny = 31

dx = Lx/(Nx-1)
dy = Ly/(Ny-1)

# ============================================================
# Material properties (Steel)
# ============================================================

k = 45.0           # W/m-K
rho = 7850.0       # kg/m3
cp = 470.0         # J/kg-K

alpha = k/(rho*cp)

# ============================================================
# Convection
# ============================================================

h = 25.0           # W/m2-K
T_inf = 25.0       # Ambient temperature

# ============================================================
# Initial condition
# ============================================================

T_initial = 100.0

T = np.ones((Ny, Nx))*T_initial

# ============================================================
# Time stepping
# ============================================================

Fo_x = 0.20
Fo_y = 0.20

dt = min(Fo_x*dx**2/alpha,
         Fo_y*dy**2/alpha)

print("Time step =", dt)

total_time = 2000      # seconds
nsteps = int(total_time/dt)

# ============================================================
# Visualization
# ============================================================

plt.ion()

for step in range(nsteps):

    Told = T.copy()

    # --------------------------------------------------------
    # Interior nodes
    # --------------------------------------------------------

    for j in range(1, Ny-1):
        for i in range(1, Nx-1):

            d2Tdx2 = (Told[j,i+1]-2*Told[j,i]+Told[j,i-1])/dx**2

            d2Tdy2 = (Told[j+1,i]-2*Told[j,i]+Told[j-1,i])/dy**2

            T[j,i] = Told[j,i] + alpha*dt*(d2Tdx2 + d2Tdy2)

    # --------------------------------------------------------
    # Left insulated
    # --------------------------------------------------------

    T[:,0] = T[:,1]

    # --------------------------------------------------------
    # Right insulated
    # --------------------------------------------------------

    T[:,-1] = T[:,-2]

    # --------------------------------------------------------
    # Bottom convection
    # --------------------------------------------------------

    for i in range(1,Nx-1):

        conduction = Told[1,i]

        T[0,i] = (
            conduction +
            (h*dy/k)*T_inf
        )/(1 + h*dy/k)

    # --------------------------------------------------------
    # Top convection
    # --------------------------------------------------------

    for i in range(1,Nx-1):

        conduction = Told[-2,i]

        T[-1,i] = (
            conduction +
            (h*dy/k)*T_inf
        )/(1 + h*dy/k)

    # --------------------------------------------------------
    # Corners
    # --------------------------------------------------------

    T[0,0] = (T[0,1]+T[1,0])/2
    T[0,-1] = (T[0,-2]+T[1,-1])/2
    T[-1,0] = (T[-2,0]+T[-1,1])/2
    T[-1,-1] = (T[-2,-1]+T[-1,-2])/2

    # --------------------------------------------------------
    # Plot every 100 steps
    # --------------------------------------------------------

    if step % 100 == 0:

        plt.clf()

        plt.contourf(T,30,cmap='jet')

        plt.colorbar(label='Temperature (°C)')

        plt.title(f'Time = {step*dt:.1f} s')

        plt.xlabel('x')

        plt.ylabel('y')

        plt.pause(0.01)

plt.ioff()
plt.show()